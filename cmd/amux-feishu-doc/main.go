// amux-feishu-doc renders the actual Feishu help registry in both languages.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/amuxos/amux/internal/bridge/command"
	"github.com/amuxos/amux/internal/distribution"
	"github.com/amuxos/amux/internal/i18n"
)

func render(locale i18n.Locale, catalog *i18n.Catalog) ([]byte, error) {
	choose := func(en, zh string) string {
		if locale == i18n.Chinese {
			return zh
		}
		return en
	}
	var out strings.Builder
	out.WriteString("<!-- Generated by make feishu-doc; DO NOT EDIT. -->\n\n")
	fmt.Fprintf(&out, "# %s\n\n", choose("Feishu command reference", "飞书命令参考"))
	out.WriteString("[English](feishu-commands.md) | [简体中文](feishu-commands.zh-CN.md)\n\n")
	out.WriteString(choose(
		"Commands below come from the same registry and translations as Feishu's context help. In groups, address commands to the bot. The current mode, Agent capabilities and authorization still determine whether an action can run. Chinese command phrases remain literal command tokens in both languages.\n\nBot-wide singleton mode uses `/amux` for conversation management and rejects topic-style `/run`, `/bind` and `/stop`. `/compact`, `/clear` and `/skill` require a supporting Agent. There is no supported `/schedule` or `/sched` topic command; use Agent tools or the operator CLI.\n\n",
		"以下命令来自飞书场景帮助使用的同一注册表与翻译词表。在群中应将命令发给机器人；当前模式、Agent 能力和授权仍决定操作能否执行。中文命令短语在两种语言中都保留为真实命令字面量。\n\n机器人级 singleton 模式通过 `/amux` 管理对话，拒绝话题式 `/run`、`/bind` 和 `/stop`。`/compact`、`/clear`、`/skill` 需要 Agent 支持。话题不支持 `/schedule` 或 `/sched`，应使用 Agent 工具或运维 CLI。\n\n"))
	for _, scope := range []struct {
		id command.Scope
		en string
		zh string
	}{
		{command.ScopePrivate, "Private chat", "私聊"},
		{command.ScopeGroup, "Group chat", "群聊"},
		{command.ScopeFreshTopic, "New topic", "新话题"},
		{command.ScopeActiveTopic, "Active bound topic", "已绑定的活跃话题"},
	} {
		fmt.Fprintf(&out, "## %s\n\n", choose(scope.en, scope.zh))
		out.WriteString(choose("| Command | Meaning |\n", "| 命令 | 含义 |\n"))
		out.WriteString("| --- | --- |\n")
		for _, item := range command.Help(scope.id) {
			key := "management.help." + string(scope.id) + "." + string(item.ID)
			var args []any
			if scope.id == command.ScopeActiveTopic && item.ID == command.CommandSkill {
				args = []any{distribution.CodexCompatibleLabel}
			}
			description := catalog.Format(locale, key, args...)
			if description == key || strings.Contains(description, "%!") {
				return nil, fmt.Errorf("invalid %s translation for %s", locale, key)
			}
			fmt.Fprintf(&out, "| `%s` | %s |\n", strings.ReplaceAll(item.Command, "|", "\\|"), strings.ReplaceAll(description, "|", "\\|"))
		}
		out.WriteString("\n")
	}
	return []byte(strings.TrimRight(out.String(), "\n") + "\n"), nil
}

func main() {
	language := flag.String("language", "en", "documentation language: en or zh-CN")
	output := flag.String("output", "docs/reference/feishu-commands.md", "Markdown output path")
	check := flag.Bool("check", false, "reject stale generated output")
	flag.Parse()
	err := run(*language, *output, *check)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(language, output string, check bool) error {
	if language != "en" && language != "zh-CN" {
		return fmt.Errorf("unsupported language %q", language)
	}
	en, err := os.ReadFile("internal/bridge/locales/en.json")
	if err != nil {
		return err
	}
	zh, err := os.ReadFile("internal/bridge/locales/zh-CN.json")
	if err != nil {
		return err
	}
	catalog, err := i18n.New(en, zh)
	if err != nil {
		return err
	}
	want, err := render(i18n.Locale(language), catalog)
	if err != nil {
		return err
	}
	if check {
		got, err := os.ReadFile(output)
		if err != nil {
			return err
		}
		if !bytes.Equal(got, want) {
			return fmt.Errorf("%s is stale; run make feishu-doc", output)
		}
		return nil
	}
	return os.WriteFile(output, want, 0o644)
}
