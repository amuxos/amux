#!/usr/bin/env python3
"""Generate bilingual reader indexes and check the published documentation set."""
import argparse
import json
import posixpath
import re
import shlex
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
ROOT_PAGES = {'README.md', 'CONTEXT.md', 'CONTRIBUTING.md', 'THIRD_PARTY_NOTICES.md', 'examples/README.md'}
EXCLUDED = {'reports', 'superpowers'}
LANGS = ('en', 'zh-CN')


def localized(source, lang):
    return source if lang == 'en' else source.removesuffix('.md') + '.zh-CN.md'


def load_catalog(root):
    data = json.loads((root / 'docs/navigation.json').read_text())
    if data.get('version') != 1 or not data.get('groups'):
        raise ValueError('navigation.json: expected version 1 and nonempty groups')
    seen, group_ids = set(), set()
    for group in data['groups']:
        if group['id'] in group_ids:
            raise ValueError('duplicate group: ' + group['id'])
        group_ids.add(group['id'])
        if not group.get('pages'):
            raise ValueError('empty group: ' + group['id'])
        for item in [group, *group['pages']]:
            if any(not isinstance(item.get('title', {}).get(lang), str) or not item['title'][lang].strip() for lang in LANGS):
                raise ValueError('missing bilingual navigation title')
        for page in group['pages']:
            source = page['source']
            path = Path(source)
            if path.is_absolute() or '..' in path.parts or str(path) != source or not source.endswith('.md') or source.endswith('.zh-CN.md'):
                raise ValueError('invalid source: ' + source)
            if source in seen or source == 'docs/README.md':
                raise ValueError('duplicate/reserved source: ' + source)
            if page.get('status', 'current') not in {'current', 'target', 'historical', 'generated'}:
                raise ValueError('invalid status: ' + source)
            seen.add(source)
    discovered = ROOT_PAGES | {p.relative_to(root).as_posix() for p in (root / 'docs').rglob('*.md')
        if p.relative_to(root / 'docs').parts[0] not in EXCLUDED and not p.name.endswith('.zh-CN.md') and p != root / 'docs/README.md'}
    if seen != discovered:
        raise ValueError(f'catalog coverage: unlisted={sorted(discovered-seen)}, missing={sorted(seen-discovered)}')
    for source in sorted(seen | {'docs/README.md'}):
        for lang in LANGS:
            file = root / localized(source, lang)
            if not file.is_file():
                raise ValueError('missing translation/source: ' + str(file))
            body = file.read_text()
            if any(Path(localized(source, other)).name not in body for other in LANGS):
                raise ValueError('missing reciprocal language links: ' + str(file))
    return data


def render_index(data, lang):
    zh = lang == 'zh-CN'
    lines = ['<!-- Generated by make docs-index from docs/navigation.json; DO NOT EDIT. -->', '',
        '<a id="文档导航"></a>', '', '# amux 文档' if zh else '# amux documentation', '',
        '[English](README.md) | [简体中文](README.zh-CN.md)', '',
        '从飞书完成工作开始阅读。已有机器人时，直接进入“对话与追问”；接入负责人先看机器人教程。产品模型供维护者查阅，描述身份、边界与当前实现。' if zh else
        'Start with work in Feishu. If you already have a bot, open Conversations and follow-ups; operators can start with bot setup. Product models describe identities, boundaries and current implementation for maintainers.', '']
    for group in data['groups']:
        # Preserve links to the former reader index while changing its headings.
        aliases = {'start': ['get-started', '入门'], 'maintainers': ['product-models', '产品模型', 'guides-and-design', '指南与设计', 'project', '项目'],
                   'operations': ['operations', '运维'], 'reference': ['参考']}
        lines.extend(f'<a id="{anchor}"></a>' for anchor in aliases.get(group['id'], []))
        lines.append('')
        lines.extend(['## ' + group['title'][lang], ''])
        for page in group['pages']:
            path = posixpath.relpath(localized(page['source'], lang), 'docs')
            status = page.get('status')
            label = {'target': ('target specification', '目标规格'), 'historical': ('historical record', '历史记录'), 'generated': ('generated', '自动生成')}.get(status)
            tag = (' — ' + label[zh]) if label else ''
            lines.append(f"- [{page['title'][lang]}]({path}){tag}")
        lines.append('')
    lines.extend(['---', '',
        '中英文配对维护。`make docs` 生成参考与本索引，`make docs-check` 检查漂移。网站按同一目录清单同步；历史报告不作为当前能力承诺。具体流程见上面的文档维护指南。' if zh else
        'Maintain English/Chinese pairs together. `make docs` generates references and this index; `make docs-check` checks drift. The website consumes the same catalog. Historical reports do not promise current capabilities. See the documentation maintenance guide above.', ''])
    return '\n'.join(lines)


def outside_fences(body):
    marker = None
    for line in body.splitlines():
        m = re.match(r'^\s{0,3}(`{3,}|~{3,})(.*)$', line)
        if m:
            token, rest = m.groups()
            if marker is None:
                marker = token
            elif token[0] == marker[0] and len(token) >= len(marker) and not rest.strip():
                marker = None
            continue
        if marker is None:
            # Inline code can demonstrate links without making them navigable.
            yield re.sub(r'(`+).*?\1', '', line)


def check_links(root, source, body):
    errors = []
    for line in outside_fences(body):
        urls = re.findall(r'!?\[[^\]]*\]\(([^\s)]+)(?:\s+"[^"]*")?\)', line)
        urls += re.findall(r'^\s*\[[^\]]+\]:\s*(\S+)', line)
        urls += re.findall(r'(?:href|src)=[\'\"]([^\'\"]+)[\'\"]', line)
        for url in urls:
            parsed = urlsplit(url.strip('<>'))
            if parsed.scheme or parsed.netloc or not parsed.path:
                continue
            target = (root / source).parent / unquote(parsed.path)
            if not target.exists():
                errors.append(f'{source}: missing link target {url}')
    return errors


def command_contract(reference):
    commands = {}
    for part in re.split(r'(?=^## `amux)', reference, flags=re.M):
        match = re.match(r'## `([^`]+)`', part)
        if not match:
            continue
        flags = set()
        for row in part.splitlines():
            if row.startswith('| `-'):
                flags.update(re.findall(r'(?<!\w)--?[a-zA-Z][\w-]*', row.split('|')[1]))
        usage = re.search(r'```text\n(.*?)\n```', part, re.S)
        tail = usage[1].removeprefix(match[1]).replace('[flags]', '').strip() if usage else ''
        commands[match[1]] = (flags, bool(tail))
    return commands


def check_commands(source, body, commands):
    """Check direct amux lines in sh/bash fences, never execute examples.

    Deliberately excludes prose, shell expansion, native-agent arguments after --,
    and quoted prompt contents. It checks names/flags, not argument semantics.
    """
    errors = []
    for block in re.findall(r'^```(?:sh|bash)\s*\n(.*?)^```\s*$', body, re.M | re.S):
        for line in block.replace('\\\n', ' ').splitlines():
            if not line.strip().startswith('amux '):
                continue
            try:
                tokens = shlex.split(line, comments=True)
            except ValueError as exc:
                errors.append(f'{source}: invalid shell example: {exc}')
                continue
            if '--' in tokens:
                tokens = tokens[:tokens.index('--')]
            candidates = [name for name in commands if tokens[:len(name.split())] == name.split()]
            name = max(candidates, key=len, default='')
            if not name:
                errors.append(f'{source}: unknown command: {line}')
                continue
            flags, positional = commands[name]
            allowed = flags | commands.get('amux', (set(), False))[0]
            for token in tokens[len(name.split()):]:
                if token.startswith('-') and token.split('=',1)[0] not in allowed:
                    errors.append(f'{source}: unknown flag {token} for {name}')
            # A pure group has no positional args; do not mistake an unknown
            # subcommand for a valid invocation of that group.
            rest = tokens[len(name.split()):]
            if not positional and rest and not rest[0].startswith('-'):
                errors.append(f'{source}: unknown subcommand after {name}: {rest[0]}')
    return errors


def validate(root, data):
    errors = []
    commands = command_contract((root/'docs/reference/cli.md').read_text())
    for group in data['groups']:
        for page in group['pages']:
            for lang in LANGS:
                source = localized(page['source'], lang)
                body = (root/source).read_text()
                errors += check_links(root, source, body)
                if source.startswith(('docs/tutorials/', 'docs/guides/', 'docs/operations/maintenance', 'docs/operations/troubleshooting')):
                    errors += check_commands(source, body, commands)
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        data = load_catalog(ROOT)
        errors = validate(ROOT, data)
        for lang in LANGS:
            path = ROOT/localized('docs/README.md',lang)
            expected = render_index(data,lang)
            if args.check:
                if path.read_text() != expected:
                    errors.append(f'{path}: stale; run make docs-index')
            elif not errors:
                path.write_text(expected)
        if errors:
            raise ValueError('\n'.join(errors))
    except (ValueError, KeyError, OSError) as exc:
        parser.exit(1, f'docs: {exc}\n')
    print('docs: catalog, bilingual pairs, local file links and command examples OK')


if __name__ == '__main__':
    main()
