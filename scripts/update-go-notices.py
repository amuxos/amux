#!/usr/bin/env python3
"""Collect upstream license/notice files for the public module's pinned Go requirements."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys


ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "third_party/go-notices.txt"
LEGAL_FILE = re.compile(
    r"(?:LICEN[SC]E|COPYING|NOTICE|COPYRIGHT|PATENTS|AUTHORS|UNLICENSE)(?:[.-].*)?",
    re.IGNORECASE,
)


def go(*args):
    return subprocess.check_output(
        ["go", *args], cwd=ROOT, env={**os.environ, "GOWORK": "off"}, text=True
    )


def json_stream(text):
    decoder = json.JSONDecoder()
    while text.strip():
        value, end = decoder.raw_decode(text.lstrip())
        yield value
        text = text.lstrip()[end:]


def legal_files(directory):
    found = []
    for parent, directories, files in os.walk(directory):
        directories[:] = sorted(
            name for name in directories
            if name not in {"test", "tests", "testdata", "fuzz", "vendor"}
            and not name.startswith(".")
        )
        for name in sorted(files):
            if LEGAL_FILE.fullmatch(name):
                found.append(Path(parent) / name)
    return sorted(found)


def section(name, source, files, directory):
    parts = ["=" * 78, name, "Source: " + source, ""]
    for file in files:
        parts.extend(["--- " + file.relative_to(directory).as_posix() + " ---", ""])
        # Keep the upstream wording; normalize only line endings and trailing space.
        parts.extend(line.rstrip() for line in file.read_text(encoding="utf-8-sig").splitlines())
        parts.append("")
    return "\n".join(parts) + "\n"


def render():
    manifest = json.loads(go("mod", "edit", "-json"))
    if manifest.get("Replace"):
        raise ValueError("resolve public go.mod replacements before collecting upstream notices")
    requirements = sorted(manifest.get("Require", []), key=lambda item: item["Path"])
    pinned = [item["Path"] + "@" + item["Version"] for item in requirements]
    downloads = {
        item["Path"]: item for item in json_stream(go("mod", "download", "-json", *pinned))
    }
    digest = hashlib.sha256((ROOT / "go.mod").read_bytes()).hexdigest()
    result = [
        "Go dependency licenses and notices / Go 依赖许可证与声明\n"
        "Generated by scripts/update-go-notices.py; do not edit by hand.\n"
        "由 scripts/update-go-notices.py 生成，请勿手工修改。\n"
        f"go.mod SHA-256: {digest}\n\n"
        "Includes every pinned requirement in go.mod; an individual binary may use a subset.\n"
        "包含 go.mod 的全部固定版本依赖；单个二进制可能仅使用其中一部分。\n"
        "Upstream notices retain their own terms. These components are not relicensed by amux.\n"
        "上游声明保留各自条款，amux 不更改这些组件的许可证。\n"
        "Source links provide the exact upstream module archives, including MPL-covered sources.\n"
        "源码链接提供对应版本的上游 module 归档，包括 MPL 许可覆盖的源码。\n\n",
    ]
    goroot = Path(go("env", "GOROOT").strip())
    # Homebrew keeps the Go license beside libexec rather than inside GOROOT.
    go_license = next(
        (file for file in (goroot / "LICENSE", goroot.parent / "LICENSE") if file.is_file()),
        None,
    )
    if go_license is None:
        raise ValueError("Go installation is missing its LICENSE file")
    result.append(section(
        "Go runtime and standard library", "https://go.dev/src/",
        [go_license], go_license.parent,
    ))
    for requirement in requirements:
        path, version = requirement["Path"], requirement["Version"]
        module = downloads.get(path, {})
        if module.get("Error") or not module.get("Dir") or module.get("Version") != version:
            raise ValueError(f"cannot resolve {path}@{version}: {module.get('Error', 'missing module directory')}")
        directory = Path(module["Dir"])
        files = legal_files(directory)
        if not any(file.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "UNLICENSE")) for file in files):
            raise ValueError(f"no upstream license found for {path}@{version}; review it manually")
        escaped = "".join("!" + c.lower() if c.isupper() else c for c in path)
        source = f"https://proxy.golang.org/{escaped}/@v/{version}.zip"
        result.append(section(path + " " + version, source, files, directory))
    return "".join(result).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in collection is stale")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != content:
            sys.exit("Go notices are stale; run python3 scripts/update-go-notices.py")
        print("Go third-party notices are current")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content, encoding="utf-8")
        print("Updated " + str(OUTPUT.relative_to(ROOT)))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        sys.exit(str(error))
