func TestConfigReferenceCatalogIsValid(t *testing.T) {
	seen := map[string]bool{}
	for _, option := range ConfigOptions() {
		if strings.TrimSpace(option.Section) == "" || strings.TrimSpace(option.Key) == "" ||
			strings.TrimSpace(option.Type) == "" || strings.TrimSpace(option.Default) == "" ||
			strings.TrimSpace(option.Description) == "" {
			t.Fatalf("incomplete config option: %+v", option)
		}
		if seen[option.Key] {
			t.Fatalf("duplicate config option %q", option.Key)
		}
		seen[option.Key] = true
	}
	for _, key := range ManagedConfigKeys() {
		if !seen[key] {
			t.Fatalf("managed key %q is absent from config reference", key)
		}
	}
}

func TestConfigReferenceCoversConfigReads(t *testing.T) {
	ctx := build.Default
	ctx.BuildTags = append(ctx.BuildTags, configReferenceBuildTags...)
	pkg, err := ctx.ImportDir(".", 0)
	if err != nil {
		t.Fatal(err)
	}
	var sources strings.Builder
	for _, name := range pkg.GoFiles {
		source, err := os.ReadFile(name)
		if err != nil {
			t.Fatalf("read %s: %v", name, err)
		}
		sources.Write(source)
		sources.WriteByte('\n')
	}
	source := []byte(sources.String())
	options := ConfigOptions()
	documented := func(key string) bool {
		for _, option := range options {
			if option.Key == key || strings.HasPrefix(option.Key, key+".") {
				return true
			}
		}
		return false
	}
	staticKey := regexp.MustCompile(`"((?:hub|runtime|cli|mcp|bridge|provider|adapter)\.[a-z0-9_.<>-]+)"`)
	for _, match := range staticKey.FindAllSubmatch(source, -1) {
		key := string(match[1])
		if strings.HasSuffix(key, ".") || documented(key) {
			continue
		}
		t.Errorf("config source reads undocumented key or section %q; add it to ConfigOptions", key)
	}

	// Dynamic getters build keys as base + ".field" or prefix + "field".
	// Check each function against its exact documented key family so a field
	// with the same name in another family cannot hide an omission.
	dynamicField := regexp.MustCompile(`(?:base\s*\+\s*"\.|prefix\s*\+\s*")([a-z][a-z0-9_]*)"`)
	dynamicFamilies := map[string]string{
		"GetBridgeFeishuBotE2EForProfile":            "bridge.feishu.profiles.<profile>.bot_e2e.",
		"GetBridgeFeishuDocumentCommentsForProfile":  "bridge.feishu.profiles.<profile>.document_comments.",
		"GetBridgeFeishuBotToBotForProfile":          "bridge.feishu.profiles.<profile>.bot_to_bot.",
		"GetBridgeFeishuGroupWatchForProfile":        "bridge.feishu.profiles.<profile>.group_watch.",
		"GetBridgeFeishuPresentationForProfile":      "bridge.feishu.profiles.<profile>.presentation.",
		"GetBridgeFeishuWorkspaceDefaultsForProfile": "bridge.feishu.profiles.<profile>.workspace_defaults.",
		"GetStructuredProviderForProvider":           "provider.structured.<provider>.",
	}
	for function, prefix := range dynamicFamilies {
		body := configFunctionSource(t, string(source), function)
		for _, match := range dynamicField.FindAllStringSubmatch(body, -1) {
			key := prefix + match[1]
			if !documented(key) {
				t.Errorf("%s reads undocumented dynamic key %q; add it to ConfigOptions", function, key)
			}
		}
	}
}

func configFunctionSource(t *testing.T, source, name string) string {
	t.Helper()
	start := strings.Index(source, "func "+name+"(")
	if start < 0 {
		t.Fatalf("config source is missing %s", name)
	}
	rest := source[start:]
	if next := strings.Index(rest[1:], "\nfunc "); next >= 0 {
		return rest[:next+1]
	}
	return rest
}

func TestRenderedConfigurationReferenceHasGeneratedHeader(t *testing.T) {
	got := string(RenderConfigurationReference())
	for _, want := range []string{
		"Code generated by make config-doc; DO NOT EDIT.",
		"# amux 配置参考",
		"`bridge.feishu.bot_to_bot.max_turns_per_thread`",
		"`bridge.feishu.group_watch.max_active_sessions_per_chat`",
		"`bridge.feishu.group_watch.thinking_process`",
		"`bridge.feishu.presentation.thinking_process`",
		"`bridge.feishu.profiles.<profile>.interaction.mode`",
		"`bridge.feishu.profiles.<profile>.group_watch.thinking_process`",
		"`bridge.feishu.profiles.<profile>.presentation.thinking_process`",
		"`runtime.session_reclaim.feishu.prune_after_seconds`",
		"`isolation.global_env`",
		"`provider.structured.<provider>.turn_idle_timeout_seconds`",
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("rendered config reference missing %q", want)
		}
	}
}
