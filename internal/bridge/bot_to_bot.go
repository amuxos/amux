// botCoordinationState owns bot-to-bot settings and external bot catalog cache.
type botCoordinationState struct {
	botToBotSettingsMu     sync.Mutex
	botToBotMu             sync.RWMutex
	botToBot               config.BridgeFeishuBotToBotConfig
	externalBotCatalogMu   sync.Mutex
	externalBotCatalogSeen map[string]time.Time
}

// tryCompleteExternalBotExchange is deliberately narrower than the legacy
// Bot-to-Bot router. It runs before test envelopes or identity projection so a
// reply from the expected Bot can only become external_untrusted result data.
func (b *Bridge) tryCompleteExternalBotExchange(msg *larkim.EventMessage, botOpenID, text string) (bool, error) {
	if b == nil || msg == nil || b.db == nil {
		return false, nil
	}
	botOpenID = strings.TrimSpace(botOpenID)
	currentBotOpenID := ""
	if b.secrets != nil {
		currentBotOpenID = strings.TrimSpace(b.secrets.BotOpenId)
	}
	chatType := strings.TrimSpace(stringPtr(msg.ChatType))
	if botOpenID == "" || botOpenID == currentBotOpenID || (chatType != "group" && chatType != "topic_group") || len(msg.Mentions) == 0 {
		return false, nil
	}
	mention := b.messageBotMentionInfo(msg)
	if !mention.Mentioned {
		return false, nil
	}
	// A strictly recognized amux delegation card is a new inbound task, not a
	// reply to an earlier outbound exchange. Classify it before exchange
	// correlation so a target Bot cannot accidentally complete the exchange by
	// delegating another task back to us in the same thread.
	if _, amuxDelegation := b.stripAmuxExternalBotDelegationEnvelope(msg, botOpenID, text); amuxDelegation {
		return false, nil
	}
	// The event's structured mention tokens are sufficient to remove the
	// current Bot prefix. Running the entire result through display-name
	// normalization would split and rejoin on whitespace, destroying exact
	// line breaks and indentation before the Coordinator can validate them.
	routedText := b.stripCurrentBotMention(text, mention)
	if routedText == "" {
		return false, nil
	}
	msgID := strings.TrimSpace(stringPtr(msg.MessageId))
	rootID := messageRootID(msg)
	if rootID == "" {
		rootID = msgID
	}
	if rootID == "" || msgID == "" || !b.botToBotSnapshot().Enabled {
		return false, nil
	}
	mode, err := b.interactionModeForChat(strings.TrimSpace(stringPtr(msg.ChatId)))
	if err != nil || mode != config.FeishuInteractionThread {
		return false, err
	}
	return b.db.CompleteExternalBotExchangeReply(b.currentBridgeId(), rootID, botOpenID, msgID, routedText, time.Now().UTC())
}

func (b *Bridge) handleExternalBotMessage(ctx context.Context, msg *larkim.EventMessage, botOpenID, text string) (retErr error) {
	if b == nil || msg == nil || b.db == nil {
		return nil
	}
	botOpenID = strings.TrimSpace(botOpenID)
	currentBotOpenID := ""
	if b.secrets != nil {
		currentBotOpenID = strings.TrimSpace(b.secrets.BotOpenId)
	}
	if botOpenID == "" || botOpenID == currentBotOpenID {
		return nil
	}
	chatType := strings.TrimSpace(stringPtr(msg.ChatType))
	if chatType != "group" && chatType != "topic_group" {
		return nil
	}
	// Bot calls require a structured platform mention. Text that merely looks
	// like @name must never cross this trust boundary.
	if len(msg.Mentions) == 0 {
		return nil
	}
	mention := b.messageBotMentionInfo(msg)
	if !mention.Mentioned {
		return nil
	}
	routedText, amuxDelegation := b.stripAmuxExternalBotDelegationEnvelope(msg, botOpenID, text)
	if amuxDelegation {
		// The fixed first/last blocks are transport metadata generated by another
		// amux Bridge. Keep them visible in Feishu for unknown Bot interoperability,
		// but do not turn them into business instructions for an amux Agent.
		text = routedText
		mention.PreserveText = true
		mention.AmuxDelegation = true
	} else {
		text = normalizeMentionTokens(text, mention.Replacements)
		routedText = b.stripCurrentBotMention(text, mention)
	}
	if routedText == "" {
		return nil
	}
	chatID := strings.TrimSpace(stringPtr(msg.ChatId))
	msgID := strings.TrimSpace(stringPtr(msg.MessageId))
	rootID := messageRootID(msg)
	if rootID == "" {
		rootID = msgID
	}
	if chatID == "" || rootID == "" || msgID == "" {
		return nil
	}
	botToBot := b.botToBotSnapshot()
	if !botToBot.Enabled {
		return nil
	}
	mode, err := b.interactionModeForChat(strings.TrimSpace(stringPtr(msg.ChatId)))
	if err != nil || mode != config.FeishuInteractionThread {
		return err
	}
	if !amuxDelegation {
		if handled, err := b.db.CompleteExternalBotExchangeReply(b.currentBridgeId(), rootID, botOpenID, msgID, routedText, time.Now().UTC()); handled || err != nil {
			return err
		}
	}
	if strings.HasPrefix(routedText, "/") {
		return nil
	}
	ws, err := b.currentWorkspace(chatID)
	if err != nil {
		return err
	}
	if ws.Mode != WorkspaceModeShared {
		return nil
	}
	if b.isTurnActive(rootID) {
		return nil
	}
	claim, err := b.db.ClaimBotTurn(b.currentBridgeId(), chatID, rootID, msgID, botOpenID, botToBot.MaxTurnsPerThread)
	if err != nil {
		return err
	}
	if !claim.Accepted {
		if claim.Exceeded {
			return b.notifyThread(ctx, rootID, fmt.Sprintf("智能体协作已达当前话题的 %d 轮上限，已停止自动交接。", botToBot.MaxTurnsPerThread))
		}
		if claim.Busy {
			return b.notifyThread(ctx, rootID, "当前话题已有智能体协作任务在执行，本次交接未接收。")
		}
		return nil
	}
	handoffAccepted := true
	defer func() {
		if !handoffAccepted {
			return
		}
		if handoffErr := b.failPendingBotHandoff(ctx, rootID); handoffErr != nil {
			if retErr == nil {
				retErr = handoffErr
			} else {
				retErr = fmt.Errorf("Bot handoff failed: %v; return structured failure: %w", retErr, handoffErr)
			}
		}
	}()
	if err := b.db.UpsertExternalBotPeer(externalBotPeer{
		CollaboratorID: externalBotCollaboratorID(b.currentBridgeId(), chatID, botOpenID),
		BridgeID:       b.currentBridgeId(), ChatID: chatID, BotOpenID: botOpenID, LastSeenAt: time.Now().UTC(),
	}); err != nil {
		return err
	}
	mention.ExternalBot = true
	if err := b.routeToSessionInChatWithMention(ctx, chatID, rootID, msgID, botOpenID, text, mention); err != nil {
		return err
	}
	chat, err := b.db.FindByRootMsg(b.currentBridgeId(), rootID)
	if err != nil {
		return err
	}
	if chat == nil || chat.Status != ChatStatusActive {
		return nil
	}
	handoffAccepted = false
	return nil
}

func (b *Bridge) stripAmuxExternalBotDelegationEnvelope(msg *larkim.EventMessage, senderBotOpenID, text string) (string, bool) {
	if b == nil || msg == nil || b.secrets == nil {
		return "", false
	}
	currentBotOpenID := strings.TrimSpace(b.secrets.BotOpenId)
	senderBotOpenID = strings.TrimSpace(senderBotOpenID)
	if currentBotOpenID == "" || senderBotOpenID == "" {
		return "", false
	}
	if msg.Content == nil {
		return "", false
	}
	if business, ok := stripAmuxExternalBotDelegationCardWithMentions(
		*msg.Content, currentBotOpenID, senderBotOpenID, cardKitEventBotMentionIDs(msg.Mentions),
	); ok {
		return business, true
	}
	var doc struct {
		Content [][]postContent `json:"content"`
	}
	if err := json.Unmarshal([]byte(*msg.Content), &doc); err != nil || len(doc.Content) < 3 {
		return "", false
	}
	header := doc.Content[0]
	callback := doc.Content[len(doc.Content)-1]
	if !postBlockHasProtocolMarker(header) || !postBlockMentionsBot(header, currentBotOpenID) || !postBlockMentionsBot(callback, senderBotOpenID) {
		return "", false
	}
	business := extractDelegatedPostBlocks(doc.Content[1 : len(doc.Content)-1])
	if strings.TrimSpace(business) == "" {
		return "", false
	}
	return business, true
}

func stripAmuxExternalBotDelegationCard(content, targetBotOpenID, callbackBotOpenID string) (string, bool) {
	return stripAmuxExternalBotDelegationCardWithMentions(content, targetBotOpenID, callbackBotOpenID, nil)
}

func stripAmuxExternalBotDelegationCardWithMentions(content, targetBotOpenID, callbackBotOpenID string, mentionIDs map[string]string) (string, bool) {
	var message struct {
		UserDSL string `json:"user_dsl"`
	}
	if err := json.Unmarshal([]byte(content), &message); err != nil || strings.TrimSpace(message.UserDSL) == "" {
		return "", false
	}
	var card cardDoc
	if err := json.Unmarshal([]byte(message.UserDSL), &card); err != nil || card.Schema != "2.0" {
		return "", false
	}
	if answer, ok := findCardElementByID(card.Body.Elements, cardKitReplyElementID); ok {
		if callback, callbackOK := findCardElementByID(card.Body.Elements, externalBotDelegationCallbackElementID); callbackOK {
			if business, ok := stripAmuxExternalBotDelegationAnswerWithCallback(answer, callback, targetBotOpenID, callbackBotOpenID, mentionIDs); ok {
				return business, true
			}
		}
		// v0.18 initially put callback text in answer_text. Accept it while an
		// exchange created before a rolling upgrade may still be in flight.
		if business, ok := stripAmuxExternalBotDelegationAnswer(answer, targetBotOpenID, callbackBotOpenID, mentionIDs); ok {
			return business, true
		}
	}
	// v0.17 briefly emitted three dedicated elements. Keep accepting that wire
	// shape so in-flight task cards survive a rolling upgrade.
	target, targetOK := findCardElementByID(card.Body.Elements, externalBotDelegationTargetElementID)
	task, taskOK := findCardElementByID(card.Body.Elements, externalBotDelegationTaskElementID)
	callback, callbackOK := findCardElementByID(card.Body.Elements, externalBotDelegationCallbackElementID)
	if !targetOK || !taskOK || !callbackOK ||
		target.Tag != "markdown" || task.Tag != "div" || task.Text == nil || task.Text.Tag != "plain_text" || callback.Tag != "markdown" {
		return "", false
	}
	if !cardKitElementHasProtocolMarker(target) ||
		!cardKitElementMentionsBotWithMentions(target, targetBotOpenID, mentionIDs) ||
		!cardKitElementMentionsBotWithMentions(callback, callbackBotOpenID, mentionIDs) {
		return "", false
	}
	business := strings.Trim(task.Text.Content, "\r\n")
	if strings.TrimSpace(business) == "" {
		return "", false
	}
	return business, true
}

func stripAmuxExternalBotDelegationAnswerWithCallback(answer, callback cardElement, targetBotOpenID, callbackBotOpenID string, mentionIDs map[string]string) (string, bool) {
	if answer.Tag != "markdown" || answer.ElementID != cardKitReplyElementID ||
		callback.Tag != "markdown" || callback.ElementID != externalBotDelegationCallbackElementID {
		return "", false
	}
	marker := "[\u200b](" + amuxExternalBotDelegationProtocolURL() + ")"
	markerStart := strings.Index(answer.Content, marker)
	if markerStart < 0 || !cardKitElementMentionsBotWithMentions(callback, callbackBotOpenID, mentionIDs) {
		return "", false
	}
	targetBeforeMarker := false
	for _, loc := range cardKitAtTagPattern.FindAllStringIndex(answer.Content, -1) {
		if loc[1] <= markerStart && cardKitAtTagMentionsBotWithMentions(answer.Content[loc[0]:loc[1]], targetBotOpenID, mentionIDs) {
			targetBeforeMarker = true
			break
		}
	}
	if !targetBeforeMarker {
		return "", false
	}
	markerEnd := markerStart + len(marker)
	businessStartRel := strings.Index(answer.Content[markerEnd:], "\n\n")
	if businessStartRel < 0 {
		return "", false
	}
	business := strings.Trim(answer.Content[markerEnd+businessStartRel+2:], "\r\n")
	if strings.TrimSpace(business) == "" {
		return "", false
	}
	return business, true
}

func stripAmuxExternalBotDelegationAnswer(element cardElement, targetBotOpenID, callbackBotOpenID string, mentionIDs map[string]string) (string, bool) {
	if element.Tag != "markdown" || element.ElementID != cardKitReplyElementID {
		return "", false
	}
	content := element.Content
	marker := "[\u200b](" + amuxExternalBotDelegationProtocolURL() + ")"
	markerStart := strings.Index(content, marker)
	if markerStart < 0 {
		return "", false
	}
	markerEnd := markerStart + len(marker)
	targetEnd := -1
	callbackStart, callbackEnd := -1, -1
	for _, loc := range cardKitAtTagPattern.FindAllStringIndex(content, -1) {
		tag := content[loc[0]:loc[1]]
		switch {
		case loc[1] <= markerStart && cardKitAtTagMentionsBotWithMentions(tag, targetBotOpenID, mentionIDs):
			targetEnd = loc[1]
		case loc[0] >= markerEnd && cardKitAtTagMentionsBotWithMentions(tag, callbackBotOpenID, mentionIDs):
			callbackStart, callbackEnd = loc[0], loc[1]
		}
	}
	if targetEnd < 0 || callbackStart < 0 || callbackEnd < 0 {
		return "", false
	}
	businessStartRel := strings.Index(content[markerEnd:], "\n\n")
	if businessStartRel < 0 {
		return "", false
	}
	businessStart := markerEnd + businessStartRel + 2
	callbackFrameStartRel := strings.LastIndex(content[businessStart:callbackStart], "\n\n")
	if callbackFrameStartRel < 0 {
		return "", false
	}
	callbackFrameStart := businessStart + callbackFrameStartRel + 2
	if strings.TrimSpace(content[callbackEnd:]) != "。" {
		return "", false
	}
	business := strings.Trim(content[businessStart:callbackFrameStart-2], "\r\n")
	if strings.TrimSpace(business) == "" {
		return "", false
	}
	return business, true
}

func cardKitElementHasProtocolMarker(element cardElement) bool {
	for _, match := range cardKitMarkdownLinkPattern.FindAllStringSubmatch(element.Content, -1) {
		if len(match) == 3 && match[1] == "\u200b" && strings.TrimSpace(match[2]) == amuxExternalBotDelegationProtocolURL() {
			return true
		}
	}
	return false
}

func extractCardKitExternalBotDelegationVisibleText(userDSL string) string {
	userDSL = strings.TrimSpace(userDSL)
	if userDSL == "" {
		return ""
	}
	var card cardDoc
	if err := json.Unmarshal([]byte(userDSL), &card); err != nil || card.Schema != "2.0" {
		return ""
	}
	_, targetOK := findCardElementByID(card.Body.Elements, externalBotDelegationTargetElementID)
	_, taskOK := findCardElementByID(card.Body.Elements, externalBotDelegationTaskElementID)
	_, callbackOK := findCardElementByID(card.Body.Elements, externalBotDelegationCallbackElementID)
	if !targetOK && !taskOK && !callbackOK && !strings.Contains(userDSL, amuxExternalBotDelegationProtocolURL()) {
		return ""
	}
	var lines []string
	collectCardKitVisibleText(card.Body.Elements, &lines)
	return strings.TrimSpace(strings.Join(lines, "\n"))
}

func collectCardKitVisibleText(elements []cardElement, lines *[]string) {
	for _, element := range elements {
		if element.Tag == "markdown" && strings.TrimSpace(element.Content) != "" {
			text := cardKitMarkdownLinkPattern.ReplaceAllStringFunc(element.Content, func(link string) string {
				match := cardKitMarkdownLinkPattern.FindStringSubmatch(link)
				if len(match) == 3 && match[1] == "\u200b" {
					return ""
				}
				return link
			})
			text = cardKitAtTagPattern.ReplaceAllStringFunc(text, cardKitVisibleMention)
			if text = strings.TrimSpace(text); text != "" {
				*lines = append(*lines, text)
			}
		}
		if element.Tag == "div" && element.Text != nil && strings.TrimSpace(element.Text.Content) != "" {
			*lines = append(*lines, strings.Trim(element.Text.Content, "\r\n"))
		}
		collectCardKitVisibleText(element.Elements, lines)
		for _, column := range element.Columns {
			collectCardKitVisibleText(column.Elements, lines)
		}
	}
}

func cardKitVisibleMention(tag string) string {
	for _, pattern := range []*regexp.Regexp{cardKitMentionKeyPattern, cardKitMentionIDPattern} {
		match := pattern.FindStringSubmatch(tag)
		if len(match) <= 1 {
			continue
		}
		for _, value := range match[1:] {
			if value = strings.TrimSpace(value); value != "" {
				return "@" + value
			}
		}
	}
	return tag
}

func cardKitElementMentionsBot(element cardElement, botOpenID string) bool {
	return cardKitElementMentionsBotWithMentions(element, botOpenID, nil)
}

func cardKitElementMentionsBotWithMentions(element cardElement, botOpenID string, mentionIDs map[string]string) bool {
	botOpenID = strings.TrimSpace(botOpenID)
	for _, tag := range cardKitAtTagPattern.FindAllString(element.Content, -1) {
		if cardKitAtTagMentionsBotWithMentions(tag, botOpenID, mentionIDs) {
			return true
		}
	}
	return false
}

func cardKitAtTagMentionsBot(tag, botOpenID string) bool {
	return cardKitAtTagMentionsBotWithMentions(tag, botOpenID, nil)
}

func cardKitAtTagMentionsBotWithMentions(tag, botOpenID string, mentionIDs map[string]string) bool {
	botOpenID = strings.TrimSpace(botOpenID)
	if botOpenID == "" {
		return false
	}
	tag = strings.TrimSpace(tag)
	loc := cardKitAtTagPattern.FindStringIndex(tag)
	if len(loc) != 2 || loc[0] != 0 || loc[1] != len(tag) {
		return false
	}
	if cardKitMentionKeyPattern.MatchString(tag) {
		mentionKey, ok := singleCardKitMentionAttribute(cardKitMentionKeyPattern, tag)
		if !ok {
			return false
		}
		resolved, ok := mentionIDs[mentionKey]
		return ok && strings.TrimSpace(resolved) == botOpenID
	}
	rawID, hasRawID := singleCardKitMentionAttribute(cardKitMentionIDPattern, tag)
	return hasRawID && rawID == botOpenID
}

func singleCardKitMentionAttribute(pattern *regexp.Regexp, tag string) (string, bool) {
	matches := pattern.FindAllStringSubmatch(tag, -1)
	if len(matches) != 1 {
		return "", false
	}
	for _, value := range matches[0][1:] {
		if value = strings.TrimSpace(value); value != "" {
			return value, true
		}
	}
	return "", false
}

func cardKitEventBotMentionIDs(mentions []*larkim.MentionEvent) map[string]string {
	if len(mentions) == 0 {
		return nil
	}
	ids := make(map[string]string, len(mentions))
	ambiguous := make(map[string]bool)
	for _, mention := range mentions {
		if mention == nil || !strings.EqualFold(strings.TrimSpace(stringPtr(mention.MentionedType)), "bot") || mention.Id == nil {
			continue
		}
		key := strings.TrimSpace(stringPtr(mention.Key))
		openID := strings.TrimSpace(stringPtr(mention.Id.OpenId))
		if key == "" || openID == "" || ambiguous[key] {
			continue
		}
		if existing, ok := ids[key]; ok && existing != openID {
			delete(ids, key)
			ambiguous[key] = true
			continue
		}
		ids[key] = openID
	}
	return ids
}

func postBlockHasProtocolMarker(block []postContent) bool {
	for _, item := range block {
		if item.Tag == "a" && strings.TrimSpace(item.Href) == amuxExternalBotDelegationProtocolURL() {
			return true
		}
	}
	return false
}

func postBlockMentionsBot(block []postContent, botOpenID string) bool {
	botOpenID = strings.TrimSpace(botOpenID)
	for _, item := range block {
		if item.Tag == "at" && strings.TrimSpace(item.UserID) == botOpenID {
			return true
		}
	}
	return false
}

func extractDelegatedPostBlocks(blocks [][]postContent) string {
	lines := make([]string, 0, len(blocks))
	for _, block := range blocks {
		var line strings.Builder
		for _, item := range block {
			switch item.Tag {
			case "text", "a", "code_block":
				line.WriteString(item.Text)
			case "at":
				if strings.TrimSpace(item.UserName) != "" {
					line.WriteString("@")
					line.WriteString(strings.TrimSpace(item.UserName))
				}
			}
		}
		lines = append(lines, line.String())
	}
	return strings.Trim(strings.Join(lines, "\n"), "\r\n")
}

func (c *botCoordinationState) botToBotSnapshot() config.BridgeFeishuBotToBotConfig {
	if c == nil {
		return config.BridgeFeishuBotToBotConfig{}
	}
	c.botToBotMu.RLock()
	defer c.botToBotMu.RUnlock()
	return c.botToBot
}

func (b *Bridge) setBotToBotForProfile(enabled bool) error {
	if b == nil {
		return fmt.Errorf("nil bridge")
	}
	return b.setBotToBotForProfileWith(enabled, func() error {
		return config.SetBridgeFeishuBotToBot(b.ProfileName(), enabled)
	})
}

func (c *botCoordinationState) setBotToBotForProfileWith(enabled bool, persist func() error) error {
	if c == nil {
		return fmt.Errorf("nil bridge")
	}
	if persist == nil {
		return fmt.Errorf("Bot-to-Bot persistence is required")
	}
	c.botToBotSettingsMu.Lock()
	defer c.botToBotSettingsMu.Unlock()
	if err := persist(); err != nil {
		return err
	}
	c.botToBotMu.Lock()
	c.botToBot.Enabled = enabled
	c.botToBotMu.Unlock()
	return nil
}

// deliverPendingBotHandoff emits the machine-triggering post only after the
// agent turn has a final answer. The pending claim is cleared after every
// platform delivery attempt: a failed write terminates this collaboration edge
// instead of letting a later unrelated turn retry the stale callback.
func (b *Bridge) deliverPendingBotHandoff(ctx context.Context, rootMsgID, text string) error {
	if b == nil || b.db == nil || strings.TrimSpace(text) == "" {
		return nil
	}
	pending, err := b.db.PendingBotHandoff(b.currentBridgeId(), rootMsgID)
	if err != nil || pending == nil {
		return err
	}
	deliver := b.botHandoff
	if deliver == nil {
		deliver = b.sendBotHandoffToThread
	}
	deliveryErr := deliver(ctx, rootMsgID, pending.BotOpenID, text)
	_, clearErr := b.db.ClearPendingBotHandoff(b.currentBridgeId(), rootMsgID, pending.MessageID)
	if deliveryErr != nil {
		if clearErr != nil {
			return fmt.Errorf("deliver bot handoff: %v; clear pending handoff: %w", deliveryErr, clearErr)
		}
		return deliveryErr
	}
	return clearErr
}

func (b *Bridge) failPendingBotHandoff(ctx context.Context, rootMsgID string) error {
	return b.deliverPendingBotHandoff(ctx, rootMsgID, "协作失败：当前智能体未能启动或接收任务，请稍后重试。")
}

func (b *Bridge) completePendingBotHandoff(rootMsgID, messageID string) error {
	if b == nil || b.db == nil {
		return nil
	}
	_, err := b.db.ClearPendingBotHandoff(b.currentBridgeId(), rootMsgID, messageID)
	return err
}

func (b *Bridge) discardPendingBotHandoff(rootMsgID string) {
	if b == nil || b.db == nil {
		return
	}
	pending, err := b.db.PendingBotHandoff(b.currentBridgeId(), rootMsgID)
	if err != nil || pending == nil {
		return
	}
	_, _ = b.db.ClearPendingBotHandoff(b.currentBridgeId(), rootMsgID, pending.MessageID)
}
